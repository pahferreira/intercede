import { readFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { __unstable__loadDesignSystem } from "tailwindcss";
import { locales } from "../src/i18n";

const src = join(import.meta.dir, "../src");

const designSystem = await __unstable__loadDesignSystem(
	await readFile(join(src, "index.css"), "utf8"),
	{
		base: src,
		async loadStylesheet(id: string, base: string) {
			const path =
				id === "tailwindcss"
					? Bun.resolveSync("tailwindcss/index.css", src)
					: join(base, id);
			return {
				path,
				base: dirname(path),
				content: await readFile(path, "utf8"),
			};
		},
	},
);

const quoted = /"([^"\n]*)"|'([^'\n]*)'/g;
const templated = /`([^`]*)`/g;
const interpolation = /\$\{[^}]*\}/g;

const isUnknownClass = (candidate: string) =>
	/[-:]/.test(candidate) &&
	!locales.some((locale) => locale === candidate) &&
	designSystem.parseCandidate(candidate).length > 0 &&
	designSystem.candidatesToCss([candidate])[0] === null;

const unknownClasses = (source: string) => {
	const blank = (part: string) => " ".repeat(part.length);
	const bodies = [
		...[...source.matchAll(quoted)].map((match) => ({
			text: match[1] ?? match[2] ?? "",
			start: (match.index ?? 0) + 1,
		})),
		...[...source.matchAll(templated)].map((match) => ({
			text: (match[1] ?? "").replace(interpolation, blank),
			start: (match.index ?? 0) + 1,
		})),
	];
	return bodies.flatMap(({ text, start }) =>
		[...text.matchAll(/\S+/g)]
			.filter((match) => isUnknownClass(match[0]))
			.map((match) => ({
				name: match[0],
				line: source.slice(0, start + (match.index ?? 0)).split("\n").length,
			})),
	);
};

const files = [...new Bun.Glob("**/*.{ts,tsx}").scanSync({ cwd: src })]
	.filter((path) => !/\.test\.tsx?$/.test(path))
	.sort();

let found = 0;
for (const path of files) {
	const source = await readFile(join(src, path), "utf8");
	for (const { name, line } of unknownClasses(source)) {
		found++;
		console.error(
			`src/${path}:${line} \`${name}\` is not generated by the design system theme. Use a token from src/index.css, or add one there.`,
		);
	}
}

if (found > 0) {
	process.exit(1);
}
